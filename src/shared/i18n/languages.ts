export const DEFAULT_LANGUAGE = ALL_LANGUAGES[0]; // Telugu or English

export function findLanguage(code: string): LanguageOption {
  const normalized = code.toLowerCase();
  // Handle 2-letter matches or full matches (e.g., 'EN' -> 'en', 'HI' -> 'hi', 'TE' -> 'te')
  const found = ALL_LANGUAGES.find(
    (l) => l.code.toLowerCase() === normalized || l.code.toLowerCase().startsWith(normalized)
  );
  return (
    found || {
      code: normalized,
      name: code.toUpperCase(),
      nativeName: code.toUpperCase(),
      category: 'global',
      regionLabel: 'Custom',
      flag: '🌐',
    }
  );
}
